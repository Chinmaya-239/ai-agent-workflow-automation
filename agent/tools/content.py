"""WF004 - product content generation with strict 'never invent attributes' handling."""
from __future__ import annotations

import re

from ..errors import LLMError, NeedInput
from ..registry import tool

COLORS = {"red", "blue", "green", "black", "white", "yellow", "pink", "purple", "orange", "grey", "gray",
          "brown", "navy", "beige", "silver", "gold"}
MATERIALS = {"cotton", "leather", "wool", "silk", "polyester", "steel", "plastic", "wood", "nylon", "linen",
             "denim", "rubber", "glass", "ceramic", "aluminum", "aluminium", "bamboo", "suede", "canvas"}


@tool("validate_attributes", required=("attributes",))
def validate_attributes(args, tc):
    """Split attributes into provided vs missing. Product name is mandatory; others are marked missing."""
    attrs = args["attributes"] or {}
    provided = {k: str(v).strip() for k, v in attrs.items() if v not in (None, "") and str(v).strip()}
    for req in args.get("required", ["product_name"]):
        if req not in provided:
            raise NeedInput([{"name": "product_attributes",
                              "ask": f"I need at least the '{req}'. Please provide product details, e.g. "
                                     "'name: Trail Runner; category: shoes; material: mesh; color: blue; audience: runners'."}])
    expected = args.get("expected", [])
    missing = [e for e in expected if e not in provided]
    if missing:
        tc.decide(f"Missing attributes {missing} will NOT be invented; they are marked as missing in the output")
    return {"provided": provided, "missing": missing}


def _fill(template: str, values: dict) -> str:
    """'<<...{x}...>>' segments are dropped when any placeholder inside is missing."""
    def seg(m):
        inner = m.group(1)
        names = re.findall(r"\{(\w+)\}", inner)
        return inner.format(**values) if all(values.get(n) for n in names) else ""
    text = re.sub(r"<<(.*?)>>", seg, template, flags=re.S)
    names = re.findall(r"\{(\w+)\}", text)
    text = text.format(**{n: values.get(n, "") for n in names})
    return re.sub(r"\s+([.,;|])", r"\1", re.sub(r"\s{2,}", " ", text)).strip(" -|,")


@tool("generate_text", required=("field", "instructions", "attributes", "fallback_template"))
def generate_text(args, tc):
    """LLM text generation constrained to provided attributes; deterministic template fallback."""
    attrs = args["attributes"]
    provided, missing = attrs["provided"], attrs["missing"]
    if tc.llm.available:
        system = ("You write e-commerce product copy. Use ONLY the facts provided. NEVER invent or assume "
                  "features, materials, colours, sizes, dimensions, certifications, prices or claims. If an "
                  "attribute is listed as missing, do not mention it or guess it. Output only the requested text.")
        user = (f"Product attributes (verified): {provided}\nMissing attributes (do not mention): {missing}\n\n"
                f"Task: {args['instructions']}")
        try:
            text = tc.llm.text(system, user, max_tokens=400)
            tc.note(f"{args['field']}: generated by {tc.llm.name}")
            return text.strip().strip('"')
        except LLMError as e:
            tc.note(f"{args['field']}: LLM unavailable ({e}); used template fallback")
    else:
        tc.note(f"{args['field']}: template fallback (no LLM configured)")
    return _fill(args["fallback_template"], provided)


@tool("validate_text", required=("texts", "attributes"))
def validate_text(args, tc):
    """Text validation: length limits + guard against invented colour/material claims."""
    limits, attrs = args.get("limits", {}), args["attributes"]
    cleaned, warnings = {}, []
    for field, text in args["texts"].items():
        text = (text or "").strip()
        if not text:
            warnings.append(f"{field}: empty")
        lim = limits.get(field)
        if lim and len(text) > lim:
            cut = text[:lim].rsplit(" ", 1)[0].rstrip(",;:-| ")
            warnings.append(f"{field}: {len(text)} chars > limit {lim}; truncated at a word boundary")
            text = cut
        words = set(re.findall(r"[a-z]+", text.lower()))
        for key, vocab in (("color", COLORS), ("material", MATERIALS)):
            if key in attrs["missing"] and words & vocab:
                warnings.append(f"{field}: mentions {sorted(words & vocab)} but '{key}' was not provided - possible invented attribute")
        cleaned[field] = text
    if warnings:
        tc.decide("Validation warnings: " + "; ".join(warnings))
    else:
        tc.decide("All generated text passed length and invented-attribute checks")
    return {"texts": cleaned, "warnings": warnings}
